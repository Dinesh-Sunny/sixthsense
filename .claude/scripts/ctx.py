#!/usr/bin/env python3
"""ctx.py: keeps AI context files small, fresh, verified, and portable.

Stdlib only. Config: .claude/context.config.json. Run from anywhere inside the project.

  lint [FILE...]        size budgets, style, secrets, broken references (all context files when no FILE)
  lint --hook           PostToolUse mode: reads hook JSON on stdin, lints the edited file
  budget                token/line table per file plus the always-loaded (hot) total
  refs                  broken path / link / slash-command references
  stale                 freshness: last-verified age and code churn since verification
  status [--brief]      one-line health summary (used by SessionStart)
  check [--strict]      everything above + registry/adapters up to date (CI entry point)
  registry [--check]    write .claude/registry.json (index of every context item)
  sync [--check]        regenerate tool adapters (Copilot, Cursor, Gemini, context pack)
  pack [--topic NAME]   write context-pack[.NAME].md for chat tools without repo access
  commands              derive real commands from package.json / Makefile / justfile
  learn TEXT --src S [--scope project|universal] [--target FILE]
                        append a validated one-line lesson to .claude/inbox.md
  inbox                 list inbox entries
  promote               copy universal inbox entries to the playbook repo
  verify FILE...        stamp last-verified: <today> after a human/curator review
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path

CTX_VERSION = "1.1.0"
TODAY = date.today().isoformat()
GEN_MARK = "GENERATED by .claude/scripts/ctx.py"

# --------------------------------------------------------------------------- setup

def find_root() -> Path:
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env and (Path(env) / ".claude").is_dir():
        return Path(env)
    p = Path.cwd()
    for d in [p, *p.parents]:
        if (d / ".claude" / "context.config.json").is_file():
            return d
    sys.exit("ctx.py: .claude/context.config.json not found (run inside the project)")


ROOT = find_root()
CFG = json.loads((ROOT / ".claude" / "context.config.json").read_text())
STYLE = CFG["style"]

SECRET_RES = [
    re.compile(p) for p in (
        r"sk-ant-[A-Za-z0-9_-]{20,}", r"sk-[A-Za-z0-9]{32,}", r"AKIA[0-9A-Z]{16}", r"ghp_[A-Za-z0-9]{30,}",
        r"github_pat_[A-Za-z0-9_]{30,}", r"xox[baprs]-[A-Za-z0-9-]{10,}", r"-----BEGIN [A-Z ]*PRIVATE KEY-----",
        r"AIza[0-9A-Za-z_-]{35}", r"(?i)(password|secret|token)\s*[:=]\s*['\"][^'\"{}<>]{8,}['\"]",
    )
]


def rel(p: Path) -> str:
    return p.resolve().relative_to(ROOT.resolve()).as_posix()


def est_tokens(text: str) -> int:
    return (len(text) + 3) // 4


def strip_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def excluded(path: str) -> bool:
    return any(Path(path).match(g) or fnmatch_path(path, g) for g in CFG["exclude"])


def fnmatch_path(path: str, pattern: str) -> bool:
    rx = re.escape(pattern).replace(r"\*\*/", "(.*/)?").replace(r"\*\*", ".*").replace(r"\*", "[^/]*")
    return re.fullmatch(rx, path) is not None

# --------------------------------------------------------------------------- parsing

def split_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end == -1:
        return {}, text
    raw, body = text[4:end], text[end + 4:].lstrip("\n")
    fm: dict = {}
    key = None
    for line in raw.splitlines():
        if re.match(r"^\s*#", line) or not line.strip():
            continue
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).split(" #")[0].strip()
            if val in (">-", ">", "|", "|-"):
                fm[key] = ""
            elif val.startswith("[") and val.endswith("]"):
                fm[key] = [v.strip().strip("\"'") for v in val[1:-1].split(",") if v.strip()]
            elif val == "":
                fm[key] = []
            else:
                fm[key] = val.strip("\"'")
            continue
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item and key is not None and isinstance(fm.get(key), list):
            fm[key].append(item.group(1).split(" #")[0].strip().strip("\"'"))
        elif key is not None and isinstance(fm.get(key), str) and line.startswith("  "):
            fm[key] = (fm[key] + " " + line.strip()).strip()
    return fm, body


def as_list(v) -> list[str]:
    if isinstance(v, list):
        return v
    if isinstance(v, str) and v:
        return [s.strip() for s in v.split(",") if s.strip()]
    return []


def prose_lines(body: str):
    """Yield (lineno, line) for lines that count as prose: not code, comments, tables, or headings."""
    in_code = False
    for i, line in enumerate(strip_comments(body).splitlines(), 1):
        if line.lstrip().startswith("```"):
            in_code = not in_code
            continue
        if in_code or not line.strip() or line.lstrip().startswith(("|", "#", ">")):
            continue
        yield i, line


def bullets(body: str) -> list[str]:
    return [re.sub(r"^\s*(?:[-*+]|\d+\.)\s+", "", ln).strip()
            for _, ln in prose_lines(body) if re.match(r"^\s*(?:[-*+]|\d+\.)\s+", ln)]


def first_heading(body: str) -> str:
    m = re.search(r"^#\s+(.+)$", strip_comments(body), re.M)
    return m.group(1).strip() if m else ""


def last_verified(text: str) -> str | None:
    m = re.search(r"last-verified:\s*(\d{4}-\d{2}-\d{2})", text)
    return m.group(1) if m else None

# --------------------------------------------------------------------------- discovery

class Item:
    def __init__(self, path: Path, cls: str, spec: dict):
        self.path, self.cls, self.spec = path, cls, spec
        self.text = path.read_text(errors="replace")
        self.fm, self.body = split_frontmatter(self.text)
        self.visible = strip_comments(self.text)
        self.lines = len(self.visible.strip().splitlines())
        self.tokens = est_tokens(self.visible)
        self.paths = as_list(self.fm.get("paths"))
        tier = spec["tier"]
        if tier == "auto":
            tier = "warm" if self.paths else "hot"
        self.tier = tier

    @property
    def rel(self) -> str:
        return rel(self.path)


def discover() -> list[Item]:
    items, seen = [], set()
    for cls, spec in CFG["classes"].items():
        for g in spec["globs"]:
            for p in sorted(ROOT.glob(g)):
                r = rel(p)
                if p.is_file() and r not in seen and not excluded(r):
                    if cls == "skill_ref" and p.name == "SKILL.md":
                        continue
                    seen.add(r)
                    items.append(Item(p, cls, spec))
    return items


def classify(path: Path, items: list[Item]) -> Item | None:
    r = rel(path)
    return next((i for i in items if i.rel == r), None)

# --------------------------------------------------------------------------- checks

class Report:
    def __init__(self):
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def err(self, where: str, msg: str):
        self.errors.append(f"{where}: {msg}")

    def warn(self, where: str, msg: str):
        self.warnings.append(f"{where}: {msg}")

    def merge(self, other: "Report"):
        self.errors += other.errors
        self.warnings += other.warnings

    def print(self, title: str = ""):
        if title:
            print(title)
        for e in self.errors:
            print(f"  ERROR  {e}")
        for w in self.warnings:
            print(f"  warn   {w}")
        if not self.errors and not self.warnings:
            print("  ok")


def check_budget(it: Item, rep: Report):
    s = it.spec
    if it.lines > s["max_lines"]:
        rep.err(it.rel, f"{it.lines} lines > budget {s['max_lines']}. Merge, split by paths:, or demote detail to docs/knowledge/")
    if it.tokens > s["max_tokens"]:
        rep.err(it.rel, f"≈{it.tokens} tokens > budget {s['max_tokens']}")


def check_style(it: Item, rep: Report):
    if it.cls in ("knowledge", "skill_ref"):
        return  # cold docs may hold prose; only budgets apply
    for n, line in prose_lines(it.body):
        is_bullet = re.match(r"^\s*(?:[-*+]|\d+\.)\s+", line)
        words = len(line.split())
        if is_bullet and words > STYLE["max_bullet_words"] + 2:
            rep.warn(f"{it.rel}:~{n}", f"bullet has {words} words (max {STYLE['max_bullet_words']}). Split it or move the detail to a cold doc")
        if len(line) > STYLE["max_line_chars"]:
            rep.warn(f"{it.rel}:~{n}", f"line is {len(line)} chars (max {STYLE['max_line_chars']})")
    # paragraphs = blocks separated by blank lines/headings, made only of plain prose lines
    body = re.sub(r"```.*?```", "", strip_comments(it.body), flags=re.S)
    for block in re.split(r"\n\s*\n|\n(?=#)", body):
        lines = [l for l in block.splitlines() if l.strip() and not l.lstrip().startswith(("#", "|", ">"))]
        if len(lines) > STYLE["max_paragraph_lines"] and not any(re.match(r"^\s*(?:[-*+]|\d+\.)\s+", l) for l in lines):
            rep.warn(it.rel, f"prose paragraph of {len(lines)} lines (\"{lines[0][:40]}...\"). Use one-fact bullets")


def check_secrets(it: Item, rep: Report):
    for rx in SECRET_RES:
        if rx.search(it.text):
            rep.err(it.rel, f"possible secret (pattern {rx.pattern[:24]}...). Remove it NOW")


def known_commands() -> set[str]:
    names = set(CFG["builtin_slash_commands"])
    for p in ROOT.glob(".claude/skills/*/SKILL.md"):
        fm, _ = split_frontmatter(p.read_text())
        names.update({p.parent.name, fm.get("name", p.parent.name)})
    for p in ROOT.glob(".claude/commands/**/*.md"):
        r = p.relative_to(ROOT / ".claude" / "commands").with_suffix("").as_posix()
        names.add(r.replace("/", ":"))
    for p in ROOT.glob(".claude/workflows/*.js"):
        m = re.search(r"name:\s*['\"]([\w:-]+)['\"]", p.read_text())
        names.add(m.group(1) if m else p.stem)
    return names


def workspace_packages() -> set[str]:
    """Dependency names declared in any package.json (to skip module specifiers like next/image)."""
    names: set[str] = set()
    for pj in [ROOT / "package.json", *ROOT.glob("apps/*/package.json"), *ROOT.glob("packages/*/package.json")]:
        try:
            data = json.loads(pj.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        for k in ("dependencies", "devDependencies", "peerDependencies"):
            names.update(data.get(k, {}))
    return names


def check_refs(it: Item, rep: Report, cmds: set[str]):
    body = strip_comments(it.body)
    body_nocode = re.sub(r"```.*?```", "", body, flags=re.S)
    targets = set()
    for tok in re.findall(r"`([^`\n]+)`", body_nocode):
        t = tok.strip()
        if re.fullmatch(r"/[a-z][\w:-]*", t):
            if t[1:] not in cmds:
                rep.warn(it.rel, f"slash command {t} not found (skill/command/workflow)")
            continue
        if "/" not in t or re.search(r"[\s{}<>*$|]|^https?:|^~|^/|^\.\./", t) or t.startswith(("-", "@")):
            continue
        targets.add((t.rstrip("/").split(":")[0], t.endswith("/")))
    for link in re.findall(r"\]\(([^)\s]+)\)", body_nocode):
        if not re.match(r"^(https?:|#|mailto:)", link) and "{{" not in link:
            targets.add((link.split("#")[0], False))
    # Bases: repo root, the file's own dir, and the static prefix of each `paths:` glob (e.g. apps/web/).
    bases = [ROOT, it.path.parent] + [ROOT / re.split(r"[*{]", g)[0] for g in it.paths if re.split(r"[*{]", g)[0]]
    pkgs = workspace_packages()
    for t, is_dir in sorted(targets):
        if t.split("/")[0] in pkgs:
            continue  # module specifier such as next/image or react-dom/client
        if any((b / t).exists() for b in bases):
            continue
        if git_ignored([t]):
            continue  # local-only by design (e.g. config.local.json); absent on CI and fresh clones
        if is_dir:
            rep.warn(it.rel, f"convention dir `{t}/` doesn't exist yet (fine if it's a placement rule)")
        else:
            rep.err(it.rel, f"broken reference `{t}`. Update or remove it")


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.TimeoutExpired):
        return ""


def git_ignored(paths: list[str]) -> set[str]:
    return set(git("check-ignore", "--", *paths).splitlines()) if paths else set()


def check_fresh(it: Item, rep: Report):
    lv = last_verified(it.text)
    if not lv:
        if it.tier == "hot":
            rep.warn(it.rel, "no `last-verified: YYYY-MM-DD` stamp (hot files must be verified)")
        return
    age = (date.today() - datetime.strptime(lv, "%Y-%m-%d").date()).days
    if age > CFG["freshness"]["stale_days"]:
        rep.warn(it.rel, f"last verified {age} days ago. Re-verify or demote it")
    if it.paths and git("rev-parse", "--is-inside-work-tree").strip() == "true":
        n = len(git("log", "--oneline", f"--since={lv}", "--", *[p for p in it.paths if "{" not in p]).splitlines())
        if n >= CFG["freshness"]["stale_commit_threshold"]:
            rep.warn(it.rel, f"{n} commits touched its paths since {lv}. The rule may be stale")


def check_duplicates(items: list[Item], rep: Report):
    hot = [(i.rel, b) for i in items if i.tier in ("hot", "warm") and i.cls != "inbox" for b in bullets(i.body)]
    norm = [(r, b, re.sub(r"\W+", " ", b.lower()).strip()) for r, b in hot if len(b.split()) >= 5]
    for a in range(len(norm)):
        for b in range(a + 1, len(norm)):
            if norm[a][0] == norm[b][0]:
                continue
            if difflib.SequenceMatcher(None, norm[a][2], norm[b][2]).ratio() >= STYLE["duplicate_similarity"]:
                rep.warn(norm[a][0], f"near-duplicate of {norm[b][0]}: \"{norm[a][1][:60]}...\". Keep one")


def lint_items(sel: list[Item], all_items: list[Item]) -> Report:
    rep, cmds = Report(), known_commands()
    for it in sel:
        check_budget(it, rep)
        check_style(it, rep)
        check_secrets(it, rep)
        if it.cls != "inbox":
            check_refs(it, rep, cmds)
        check_fresh(it, rep)
    hot_total = sum(i.tokens for i in all_items if i.tier == "hot")
    if hot_total > CFG["hot_max_tokens"] and any(i.tier == "hot" for i in sel):
        rep.err("HOT TOTAL", f"≈{hot_total} tokens > {CFG['hot_max_tokens']} always-loaded budget. Demote something before adding")
    return rep

# --------------------------------------------------------------------------- generators

def write_if_changed(path: Path, content: str, check: bool, drift: list[str]):
    old = path.read_text() if path.exists() else None
    if old != content:
        drift.append(rel(path) if path.exists() else f"{rel(path)} (missing)")
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


def build_registry(items: list[Item]) -> dict:
    # The registry is committed, so gitignored files (CLAUDE.local.md) stay out or CI sees drift.
    local_only = git_ignored([i.rel for i in items])
    items = [i for i in items if i.rel not in local_only]
    entries = []
    def add(kind, ident, path, tier, loads, desc, it=None):
        entries.append({
            "id": ident, "type": kind, "tier": tier, "path": path, "loads_when": loads,
            "description": (desc or "")[:200],
            "lines": it.lines if it else None, "tokens": it.tokens if it else None,
            "last_verified": last_verified(it.text) if it else None,
        })
    for it in items:
        if it.cls == "rule":
            add("rule", it.path.stem, it.rel, it.tier, ("paths: " + ", ".join(it.paths)) if it.paths else "session start", first_heading(it.body), it)
        elif it.cls == "skill":
            inv = "user only" if str(it.fm.get("disable-model-invocation")).lower() in ("true", "yes", "1") else "user + model"
            add("skill", it.fm.get("name", it.path.parent.name), it.rel, "warm", f"on invoke ({inv})", it.fm.get("description"), it)
        elif it.cls == "agent":
            add("agent", it.fm.get("name", it.path.stem), it.rel, "warm", "on delegation", it.fm.get("description"), it)
        elif it.cls == "agent_memory":
            add("agent-memory", it.path.parent.name, it.rel, "warm", f"with agent {it.path.parent.name}", "", it)
        elif it.cls == "output_style":
            add("output-style", it.fm.get("name", it.path.stem), it.rel, "warm", "when selected", it.fm.get("description"), it)
        elif it.cls == "knowledge":
            add("knowledge", it.path.stem, it.rel, "cold", "on request", first_heading(it.body), it)
        elif it.cls in ("agents_md", "claude_md"):
            add("instructions", it.path.name, it.rel, "hot", "session start", first_heading(it.body), it)
    for p in sorted(ROOT.glob(".claude/workflows/*.js")):
        m = re.search(r"description:\s*['\"]([^'\"]+)", p.read_text())
        add("workflow", p.stem, rel(p), "warm", "on invoke", m.group(1) if m else "")
    for p in sorted(ROOT.glob(".claude/hooks/*.sh")):
        if p.name.startswith("_"):
            continue
        m = re.search(r"^#\s+(.+)$", "\n".join(p.read_text().splitlines()[1:3]), re.M)
        add("hook", p.stem, rel(p), "enforced", "settings.json hooks", m.group(1) if m else "")
    entries.sort(key=lambda e: (e["type"], e["id"]))
    hot = sum(i.tokens for i in items if i.tier == "hot")
    return {"$comment": f"{GEN_MARK} registry. Do not edit.", "ctx_version": CTX_VERSION,
            "hot_tokens": hot, "hot_max_tokens": CFG["hot_max_tokens"], "items": entries}


def clean_body(it: Item) -> str:
    return re.sub(r"\n{3,}", "\n\n", strip_comments(it.body)).strip()


def header(src: str) -> str:
    return f"<!-- {GEN_MARK} sync from {src}. Do not edit; edit the source and run `python3 .claude/scripts/ctx.py sync`. -->\n"


def adapters(items: list[Item]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    agents = next((i for i in items if i.rel == "AGENTS.md"), None)
    rules = [i for i in items if i.cls == "rule"]
    hot_rules, warm_rules = [r for r in rules if r.tier == "hot"], [r for r in rules if r.tier == "warm"]
    base = clean_body(agents) if agents else ""
    always = "\n\n".join(clean_body(r) for r in hot_rules)
    pointers = "\n".join(f"- `{', '.join(r.paths)}` → follow `{r.rel}`" for r in warm_rules)
    a = CFG["adapters"]
    if a.get("copilot"):
        out[ROOT / ".github/copilot-instructions.md"] = header("AGENTS.md + always-loaded rules") + f"\n{base}\n\n{always}\n"
        for r in warm_rules:
            out[ROOT / f".github/instructions/{r.path.stem}.instructions.md"] = (
                f"---\napplyTo: \"{','.join(r.paths)}\"\n---\n" + header(r.rel) + f"\n{clean_body(r)}\n")
    if a.get("cursor"):  # Cursor reads AGENTS.md natively; only rules are generated
        for r in rules:
            fm = (f"---\ndescription: \"{first_heading(r.body)}\"\nalwaysApply: true\n---\n" if r.tier == "hot" else
                  f"---\ndescription: \"{first_heading(r.body)}\"\nglobs: \"{','.join(r.paths)}\"\nalwaysApply: false\n---\n")
            out[ROOT / f".cursor/rules/{r.path.stem}.mdc"] = fm + header(r.rel) + f"\n{clean_body(r)}\n"
    if a.get("gemini"):
        out[ROOT / "GEMINI.md"] = header("AGENTS.md + rules") + f"\n{base}\n\n{always}\n\n## Path-specific rules\n\n{pointers}\n"
    if a.get("pack"):
        out[ROOT / "context-pack.md"] = build_pack(items, None)
    return out


def build_pack(items: list[Item], topic: str | None) -> str:
    agents = next((i for i in items if i.rel == "AGENTS.md"), None)
    rules = [i for i in items if i.cls == "rule"]
    parts = [header("AGENTS.md + rules + knowledge index") +
             "\n> Context pack for AI chats without repo access. Paste or upload it as project knowledge.\n",
             clean_body(agents) if agents else "",
             "\n## Always-on rules\n", *[clean_body(r) for r in rules if r.tier == "hot"]]
    warm = [r for r in rules if r.tier == "warm"]
    warm_full = ["\n## Path-specific rules\n", *[f"_Applies to `{', '.join(r.paths)}`_\n\n{clean_body(r)}" for r in warm]]
    warm_ptr = ["\n## Path-specific rules (summarized)\n", *[f"- {first_heading(r.body)}: `{', '.join(r.paths)}`" for r in warm]]
    kn = [i for i in items if i.cls == "knowledge" and i.path.name != "README.md"]
    idx = ["\n## Knowledge docs (ask for these when relevant)\n", *[f"- `{k.rel}`: {first_heading(k.body)}" for k in kn]] if kn else []
    extra = []
    if topic:
        tp = ROOT / "docs/knowledge" / f"{topic}.md"
        if not tp.exists():
            sys.exit(f"no docs/knowledge/{topic}.md")
        extra = [f"\n## Topic: {topic}\n", strip_comments(tp.read_text()).strip()]
    full = "\n\n".join(p for p in parts + warm_full + idx + extra if p)
    if est_tokens(full) > CFG["pack_max_tokens"]:
        full = "\n\n".join(p for p in parts + warm_ptr + idx + extra if p)
    return re.sub(r"\n{3,}", "\n\n", full).strip() + "\n"


def stale_generated(new: dict[Path, str]) -> list[Path]:
    olds = []
    for d in (".github/instructions", ".cursor/rules"):
        for p in (ROOT / d).glob("*"):
            if p.is_file() and p not in new and GEN_MARK in p.read_text(errors="ignore")[:600]:
                olds.append(p)
    return olds

# --------------------------------------------------------------------------- inbox

INBOX = ROOT / ".claude" / "inbox.md"
ENTRY_RE = re.compile(r"^- (\d{4}-\d{2}-\d{2}) \| (project|universal) \| (.+?) \| src: (.+?)(?: \| → (.+?))?( \[promoted [\d-]+\])?$")


def inbox_entries() -> list[re.Match]:
    if not INBOX.exists():
        return []
    return [m for m in (ENTRY_RE.match(l) for l in INBOX.read_text().splitlines()) if m]


def cmd_learn(a, items):
    text = " ".join(a.text.split())
    errs = []
    if len(text.split()) > STYLE["max_inbox_words"]:
        errs.append(f"{len(text.split())} words > {STYLE['max_inbox_words']}. State one fact, imperative, no story")
    if any(rx.search(text) for rx in SECRET_RES):
        errs.append("looks like it contains a secret")
    if "|" in text:
        errs.append("no '|' characters")
    pool = [m.group(3) for m in inbox_entries()] + [b for i in items if i.tier == "hot" for b in bullets(i.body)]
    norm = lambda s: re.sub(r"\W+", " ", s.lower()).strip()
    for p in pool:
        if difflib.SequenceMatcher(None, norm(text), norm(p)).ratio() >= STYLE["duplicate_similarity"]:
            errs.append(f"already covered: \"{p[:80]}\"")
            break
    if errs:
        print("REJECTED:\n  - " + "\n  - ".join(errs))
        return 1
    line = f"- {TODAY} | {a.scope} | {text} | src: {a.src}" + (f" | → {a.target}" if a.target else "")
    INBOX.write_text(INBOX.read_text().rstrip("\n") + "\n" + line + "\n")
    print(f"added to .claude/inbox.md: {line}")
    return 0


def cmd_promote(_a, _items):
    pb = Path(os.path.expanduser(os.environ.get("AI_PLAYBOOK_DIR", CFG["playbook_dir"])))
    target = pb / "inbox.md"
    if not target.exists():
        print(f"playbook inbox not found: {target} (set AI_PLAYBOOK_DIR)")
        return 1
    lines, moved = INBOX.read_text().splitlines(), 0
    out = []
    for l in lines:
        m = ENTRY_RE.match(l)
        if m and m.group(2) == "universal" and not m.group(6):
            with target.open("a") as f:
                f.write(f"- {m.group(1)} | universal | {m.group(3)} | src: {ROOT.name}: {m.group(4)}\n")
            l += f" [promoted {TODAY}]"
            moved += 1
        out.append(l)
    INBOX.write_text("\n".join(out) + "\n")
    print(f"promoted {moved} entr{'y' if moved == 1 else 'ies'} → {target}")
    return 0

# --------------------------------------------------------------------------- commands

def cmd_commands(_a=None, _items=None, quiet=False) -> str:
    lines = []
    pj = ROOT / "package.json"
    if pj.exists():
        pm = next((m for f, m in (("pnpm-lock.yaml", "pnpm"), ("bun.lock", "bun"), ("bun.lockb", "bun"), ("yarn.lock", "yarn")) if (ROOT / f).exists()), "npm")
        scripts = json.loads(pj.read_text()).get("scripts", {})
        lines += [f"{pm} run {k}  # {v[:70]}" for k, v in scripts.items()]
    for mf in ("Makefile", "justfile"):
        p = ROOT / mf
        if p.exists():
            tgts = re.findall(r"^([A-Za-z0-9_-]+):(?!=)", p.read_text(), re.M)
            lines += [f"{'make' if mf == 'Makefile' else 'just'} {t}" for t in dict.fromkeys(tgts)]
    txt = "\n".join(lines)
    if not quiet:
        print(txt or "no package.json / Makefile / justfile found")
    return txt

# --------------------------------------------------------------------------- CLI

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("lint"); p.add_argument("files", nargs="*"); p.add_argument("--hook", action="store_true")
    sp.add_parser("budget"); sp.add_parser("refs"); sp.add_parser("stale"); sp.add_parser("inbox")
    p = sp.add_parser("status"); p.add_argument("--brief", action="store_true")
    p = sp.add_parser("check"); p.add_argument("--strict", action="store_true")
    for n in ("registry", "sync"):
        p = sp.add_parser(n); p.add_argument("--check", action="store_true")
    p = sp.add_parser("pack"); p.add_argument("--topic")
    sp.add_parser("commands"); sp.add_parser("promote")
    p = sp.add_parser("learn"); p.add_argument("text"); p.add_argument("--src", required=True)
    p.add_argument("--scope", choices=["project", "universal"], default="project"); p.add_argument("--target")
    p = sp.add_parser("verify"); p.add_argument("files", nargs="+")
    a = ap.parse_args()
    items = discover()

    if a.cmd == "lint":
        if a.hook:
            try:
                fp = json.load(sys.stdin).get("tool_input", {}).get("file_path", "")
            except json.JSONDecodeError:
                return 0
            it = classify(Path(fp), items) if fp and Path(fp).exists() else None
            if not it:
                return 0
            rep = lint_items([it], items)
            if rep.errors:
                print("Context lint FAILED. Fix before continuing:\n- " + "\n- ".join(rep.errors + rep.warnings), file=sys.stderr)
                return 2
            if rep.warnings:
                print(json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse",
                      "additionalContext": "Context lint warnings (fix now, keep files lean):\n- " + "\n- ".join(rep.warnings)}}))
            return 0
        sel = [i for i in items if not a.files or i.rel in {rel(Path(f)) for f in a.files}]
        rep = lint_items(sel, items)
        if not a.files:
            check_duplicates(items, rep)
        rep.print(f"lint ({len(sel)} files)")
        return 1 if rep.errors else 0

    if a.cmd == "budget":
        print(f"{'tier':5} {'lines':>9} {'≈tokens':>13}  file")
        for it in sorted(items, key=lambda i: ("hot warm cold".split().index(i.tier), -i.tokens)):
            flag = " !" if it.lines > it.spec["max_lines"] or it.tokens > it.spec["max_tokens"] else ""
            print(f"{it.tier:5} {it.lines:>4}/{it.spec['max_lines']:<4} {it.tokens:>6}/{it.spec['max_tokens']:<6} {it.rel}{flag}")
        hot = sum(i.tokens for i in items if i.tier == "hot")
        print(f"\nHOT (always loaded): ≈{hot}/{CFG['hot_max_tokens']} tokens ({100 * hot // CFG['hot_max_tokens']}%)")
        return 0

    if a.cmd in ("refs", "stale"):
        rep, cmds = Report(), known_commands()
        for it in items:
            (check_refs(it, rep, cmds) if a.cmd == "refs" else check_fresh(it, rep))
        rep.print(a.cmd)
        return 1 if rep.errors else 0

    if a.cmd == "status":
        rep = lint_items(items, items)
        hot = sum(i.tokens for i in items if i.tier == "hot")
        n_inbox = len([m for m in inbox_entries() if not m.group(6)])
        drift = []
        for path, content in adapters(items).items():
            write_if_changed(path, content, True, drift)
        msg = (f"context: hot ≈{hot}/{CFG['hot_max_tokens']} tok · {len(rep.errors)} errors · {len(rep.warnings)} warnings"
               f" · inbox {n_inbox}" + (f" · {len(drift)} adapters out of sync" if drift else ""))
        if a.brief:
            hints = []
            if rep.errors: hints.append("run `python3 .claude/scripts/ctx.py lint`")
            if n_inbox >= 10 or rep.warnings or drift: hints.append("consider `/docs-garden`")
            print(msg + (" → " + "; ".join(hints) if hints else ""))
        else:
            print(msg); rep.print()
        return 0

    if a.cmd == "check":
        rep = lint_items(items, items)
        check_duplicates(items, rep)
        drift: list[str] = []
        for path, content in adapters(items).items():
            write_if_changed(path, content, True, drift)
        write_if_changed(ROOT / ".claude/registry.json", json.dumps(build_registry(items), indent=2) + "\n", True, drift)
        for d in drift:
            rep.err(d, "generated file out of date. Run `python3 .claude/scripts/ctx.py sync && ... registry`")
        rep.print(f"check ({len(items)} context files)")
        return 1 if rep.errors or (a.strict and rep.warnings) else 0

    if a.cmd == "registry":
        drift = []
        write_if_changed(ROOT / ".claude/registry.json", json.dumps(build_registry(items), indent=2) + "\n", a.check, drift)
        print(("out of date: " if a.check else "updated: ") + ", ".join(drift) if drift else "registry up to date")
        return 1 if (a.check and drift) else 0

    if a.cmd == "sync":
        new, drift = adapters(items), []
        for path, content in new.items():
            write_if_changed(path, content, a.check, drift)
        for old in stale_generated(new):
            drift.append(f"{rel(old)} (orphan)")
            if not a.check:
                old.unlink()
        print(("out of sync: " if a.check else "synced: ") + ", ".join(drift) if drift else "adapters up to date")
        return 1 if (a.check and drift) else 0

    if a.cmd == "pack":
        out = ROOT / (f"context-pack.{a.topic}.md" if a.topic else "context-pack.md")
        content = build_pack(items, a.topic)
        out.write_text(content)
        print(f"wrote {rel(out)} (≈{est_tokens(content)} tokens)")
        return 0

    if a.cmd == "inbox":
        es = inbox_entries()
        for m in es:
            print(f"{m.group(1)} [{m.group(2)}]{' (promoted)' if m.group(6) else ''} {m.group(3)}  ← {m.group(4)}")
        print(f"{len(es)} entries")
        return 0

    if a.cmd == "verify":
        for f in a.files:
            p = ROOT / f
            t = p.read_text()
            if last_verified(t):
                t = re.sub(r"last-verified:\s*\d{4}-\d{2}-\d{2}", f"last-verified: {TODAY}", t, count=1)
            elif t.startswith("---\n"):
                end = t.find("\n---", 4) + 4
                t = t[:end] + f"\n<!-- last-verified: {TODAY} -->" + t[end:]
            else:
                t = f"<!-- last-verified: {TODAY} -->\n" + t
            p.write_text(t)
            print(f"verified {f}")
        return 0

    return {"commands": lambda: (cmd_commands(), 0)[1], "learn": lambda: cmd_learn(a, items),
            "promote": lambda: cmd_promote(a, items)}[a.cmd]()


if __name__ == "__main__":
    sys.exit(main())
